"""Regenerate EXPERIMENTS_LEDGER.md from every experiment's manifest.json.

The ledger is a derived artifact: never hand-edit it, run this instead.

    python scratch/experiments/ledger.py
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _lib import experiment as exp  # noqa: E402

FOLDER_RE = re.compile(r"^(\d{3})__(\d{4}-\d{2}-\d{2})__(.+)$")
LEDGER_PATH = exp.EXPERIMENTS / "EXPERIMENTS_LEDGER.md"

STATUS_MARK = {
    "planned": "🟡", "running": "🔵", "complete": "✅",
    "abandoned": "⚪", "superseded": "🟠",
}


def _load_experiments() -> list[dict]:
    rows = []
    for p in sorted(exp.EXPERIMENTS.iterdir()):
        if not p.is_dir() or not FOLDER_RE.match(p.name):
            continue
        mpath = p / "manifest.json"
        if not mpath.exists():
            continue
        m = json.loads(mpath.read_text(encoding="utf-8"))
        m["_folder"] = p.name
        rows.append(m)
    rows.sort(key=lambda m: m.get("id", ""))
    return rows


def _short(h) -> str:
    return h[:9] if isinstance(h, str) else "—"


def build() -> Path:
    exps = _load_experiments()

    # Current core-dataset fingerprint (foundation everything is built on).
    try:
        core_fp = exp.core_fingerprint()
    except FileNotFoundError:
        core_fp = {}

    L = ["# Experiments Ledger", "",
         "_Auto-generated by `ledger.py` — do not edit by hand._", "",
         f"Total experiments: **{len(exps)}**", ""]

    # Foundation
    L += ["## Core dataset (shared foundation)", "",
          "Every experiment reads this read-only and pins its fingerprint.", "",
          "| Layer | Rows | SHA-256 (short) |", "|---|---|---|"]
    for name, meta in core_fp.items():
        L.append(f"| `{meta['file'].split('/')[-1]}` | {meta['rows']} | `{_short(meta['sha256'])}` |")
    L.append("")

    # Index
    L += ["## Index", "",
          "| ID | Date | Title | Status | Depends on | Outputs | Rationale |",
          "|---|---|---|---|---|---|---|"]
    if not exps:
        L.append("| — | — | _none yet_ | — | — | — | — |")
    for m in exps:
        mark = STATUS_MARK.get(m.get("status", ""), "")
        title = m.get("title") or m.get("slug", "")
        dep = ", ".join(m.get("depends_on") or []) or "—"
        n_out = len(m.get("outputs") or [])
        rat = (m.get("rationale") or "").replace("|", "\\|")
        if len(rat) > 70:
            rat = rat[:67] + "..."
        L.append(f"| {m.get('id','?')} | {m.get('date_created','?')} | "
                 f"[{title}]({m['_folder']}/README.md) | {mark} {m.get('status','?')} | "
                 f"{dep} | {n_out} | {rat} |")
    L.append("")

    # Dependency edges (for future cross-experiment analyses)
    edges = [(dep, m["id"]) for m in exps for dep in (m.get("depends_on") or [])]
    if edges:
        L += ["## Dependencies", "",
              "```", *[f"{a} -> {b}" for a, b in edges], "```", ""]

    # Findings digest
    with_findings = [m for m in exps if m.get("key_findings")]
    if with_findings:
        L += ["## Key findings digest", ""]
        for m in with_findings:
            L.append(f"- **{m['id']} {m.get('title') or m.get('slug')}**")
            for f in m["key_findings"]:
                L.append(f"  - {f}")
        L.append("")

    LEDGER_PATH.write_text("\n".join(L), encoding="utf-8")
    return LEDGER_PATH


if __name__ == "__main__":
    path = build()
    print(f"Wrote {path.relative_to(exp.REPO_ROOT)}")
